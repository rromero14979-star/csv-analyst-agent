"""Data robustness test: the same 5 questions on deformed copies of one CSV (needs OPENAI_API_KEY).

Each variant reproduces a problem that real CSV exports have. Ground truth is computed with pandas from the
clean data (or from the deformed values, for the variant with missing cells).

    python eval/stress_test.py "path/to/Sample - Superstore.csv"                 # all variants
    python eval/stress_test.py "path/to/Sample - Superstore.csv" --variants semicolon,currency
Outputs eval/results/stress/<variant>.csv and eval/results/stress/summary.csv
"""
import argparse
import io
import sys
import time
from pathlib import Path

import numpy as np
import pandas as pd

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from analyst.builder import run_question  # noqa: E402
from analyst.config import get_secret  # noqa: E402
from analyst.factory import create_graph, prepare_dataset  # noqa: E402
from analyst.profiling import DataLoadError, load_dataframe  # noqa: E402
from eval.grading import grade  # noqa: E402

RESULTS = ROOT / "eval" / "results" / "stress"
QUESTIONS = [
    ("What is the total sales?", "sales_total"),
    ("What is the total profit of the Furniture category?", "furniture_profit"),
    ("Which region had the highest total sales in 2017?", "region_2017"),
    ("What is the average discount?", "avg_discount"),
    ("How many unique orders are there?", "unique_orders"),
]


def truth(df: pd.DataFrame) -> dict:
    """Expected answers from a frame with the ORIGINAL column names and clean types."""
    y = pd.to_datetime(df["Order Date"], format="mixed").dt.year
    return {
        "sales_total": ("number", round(df["Sales"].sum(), 2)),
        "furniture_profit": ("number", round(df[df["Category"] == "Furniture"]["Profit"].sum(), 2)),
        "region_2017": ("text", df[y == 2017].groupby("Region")["Sales"].sum().idxmax()),
        "avg_discount": ("number", round(df["Discount"].mean(), 4)),
        "unique_orders": ("number", int(df["Order ID"].nunique())),
    }


def _money(v: float) -> str:
    return f"-${abs(v):,.2f}" if v < 0 else f"${v:,.2f}"


def variants(clean: pd.DataFrame) -> dict:
    """name -> (description, csv bytes, frame used for the ground truth)."""
    rng = np.random.RandomState(7)
    out = {"original": ("Unchanged file", clean.to_csv(index=False).encode(), clean)}
    out["semicolon"] = ("';' as separator (Excel in Spanish/European locales)",
                        clean.to_csv(index=False, sep=";").encode(), clean)
    out["european"] = ("';' separator and decimal comma (1234,56)",
                       clean.to_csv(index=False, sep=";", decimal=",").encode(), clean)
    cur = clean.copy()
    cur["Sales"], cur["Profit"] = cur["Sales"].map(_money), cur["Profit"].map(_money)
    cents = clean.assign(Sales=clean["Sales"].round(2), Profit=clean["Profit"].round(2))  # what the text shows
    out["currency"] = ("Sales and Profit as text like '$1,234.56' and '-$12.30'", cur.to_csv(index=False).encode(), cents)
    miss = clean.copy()
    for col in ("Sales", "Profit", "Discount", "Region"):
        miss.loc[rng.rand(len(miss)) < 0.08, col] = np.nan
    raw = miss.astype(object).where(miss.notna(), "")
    raw.loc[rng.rand(len(raw)) < 0.02, "Sales"] = "N/A"
    shown = miss.copy()
    shown.loc[raw["Sales"] == "N/A", "Sales"] = np.nan
    out["missing"] = ("8% empty cells in Sales, Profit, Discount, Region plus 2% 'N/A' in Sales",
                      raw.to_csv(index=False).encode(), shown)
    heads = clean.rename(columns={"Sales": " sales_usd ", "Profit": "PROFIT", "Order Date": "order_date",
                                  "Region": "REGION", "Discount": "disc.", "Order ID": "order id"})
    out["headers"] = ("Renamed, lowercase/uppercase headers with spaces (' sales_usd ', 'PROFIT', 'disc.')",
                      heads.to_csv(index=False).encode(), clean)
    out["title_rows"] = ("Three report lines above the header row",
                         b"Superstore sales export\nGenerated by ERP v2\n\n" + clean.to_csv(index=False).encode(), clean)
    dates = clean.copy()
    half = rng.rand(len(dates)) < 0.5
    dates["Order Date"] = np.where(half, dates["Order Date"].dt.strftime("%Y-%m-%d"), dates["Order Date"].dt.strftime("%m/%d/%Y"))
    out["mixed_dates"] = ("Order Date mixes 2017-11-08 and 11/08/2017", dates.to_csv(index=False).encode(), clean)
    out["trailing_column"] = ("Every line ends with ',' (an empty extra column, common in Excel exports)",
                              "\n".join(line + "," for line in clean.to_csv(index=False).splitlines()).encode(), clean)
    return out


def run_variant(name, description, data, expected_df, openai_key) -> pd.DataFrame:
    expected = truth(expected_df)
    base = {"variant": name, "description": description}
    try:
        df = load_dataframe(data)
    except DataLoadError as exc:
        return pd.DataFrame([{**base, "loaded": False, "load_note": str(exc), "correct": False} | {"question": q} for q, _ in QUESTIONS])
    kinds = {c: str(df[c].dtype) for c in df.columns if c.strip().lower() in ("sales", "sales_usd", "profit", "order date", "order_date", "discount", "disc.")}
    load_note = f"{df.shape[1]} columns; " + ", ".join(f"{k}={v}" for k, v in kinds.items())
    ctx = prepare_dataset(openai_key, df)
    graph = create_graph(openai_key, None, ctx, web_enabled=False)
    rows = []
    for question, key in QUESTIONS:
        etype, value = expected[key]
        row = pd.Series({"expected_type": etype, "expected_value": value if etype == "number" else "",
                         "expected_text": value if etype == "text" else "", "expected_columns": "", "expected_keywords": ""})
        start = time.time()
        state = run_question(graph, question)
        rows.append({**base, "loaded": True, "load_note": load_note, "question": question, "expected": value,
                     "correct": grade(row, state), "answer": state.get("answer", ""), "attempts": state.get("attempts", 0),
                     "trace": " > ".join(state.get("trace", [])), "code": state.get("code", ""),
                     "latency_s": round(time.time() - start, 2)})
        print(f"[{name}] {key:<17} correct={rows[-1]['correct']}")
    return pd.DataFrame(rows)


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("csv", help="the clean source CSV (Superstore)")
    parser.add_argument("--variants", default="", help="comma-separated subset; default all")
    args = parser.parse_args()
    openai_key = get_secret("OPENAI_API_KEY")
    if not openai_key:
        raise SystemExit("Set OPENAI_API_KEY in .env first.")
    clean = load_dataframe(args.csv)
    todo = variants(clean)
    if args.variants:
        todo = {k: v for k, v in todo.items() if k in args.variants.split(",")}
    RESULTS.mkdir(parents=True, exist_ok=True)
    for name, (description, data, expected_df) in todo.items():
        res = run_variant(name, description, data, expected_df, openai_key)
        res.to_csv(RESULTS / f"{name}.csv", index=False)

    parts = [pd.read_csv(p) for p in sorted(RESULTS.glob("*.csv")) if p.name != "summary.csv"]
    allres = pd.concat(parts, ignore_index=True)
    summary = allres.groupby(["variant", "description"], sort=False).agg(
        loaded=("loaded", "first"), correct=("correct", "sum"), n=("correct", "size"), load_note=("load_note", "first"),
    ).reset_index()
    summary.to_csv(RESULTS / "summary.csv", index=False)
    print("\n", summary[["variant", "loaded", "correct", "n", "load_note"]].to_string(index=False))


if __name__ == "__main__":
    main()
